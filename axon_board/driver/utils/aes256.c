aes256_status_t aes256_init(aes256_ctx_t* ctx, const uint8_t* key)
{
    if (!ctx || !key) {
        return AES256_ERROR_NULL_POINTER;
    }

    ctx->key_length = 32;
    key_expansion(ctx->round_key, key);
    return AES256_SUCCESS;
}

aes256_status_t aes256_encrypt_ecb(
    aes256_ctx_t* ctx,
    const uint8_t* plaintext,
    uint8_t* ciphertext,
    size_t length
)
{
    if (!ctx || !plaintext || !ciphertext) {
        return AES256_ERROR_NULL_POINTER;
    }

    if (length % 16 != 0) {
        return AES256_ERROR_INVALID_SIZE;
    }

    for (size_t i = 0; i < length; i += 16) {
        uint8_t state[16];
        memcpy(state, plaintext + i, 16);

        add_round_key(state, ctx->round_key);

        for (int round = 1; round < 14; ++round) {
            sub_bytes(state);
            shift_rows(state);
            mix_columns(state);
            add_round_key(state, ctx->round_key + round * 16);
        }

        sub_bytes(state);
        shift_rows(state);
        add_round_key(state, ctx->round_key + 224);

        memcpy(ciphertext + i, state, 16);
    }

    return AES256_SUCCESS;
}

aes256_status_t aes256_decrypt_ecb(
    aes256_ctx_t* ctx,
    const uint8_t* ciphertext,
    uint8_t* plaintext,
    size_t length
)
{
    if (!ctx || !ciphertext || !plaintext) {
        return AES256_ERROR_NULL_POINTER;
    }

    if (length % 16 != 0) {
        return AES256_ERROR_INVALID_SIZE;
    }

    for (size_t i = 0; i < length; i += 16) {
        uint8_t state[16];
        memcpy(state, ciphertext + i, 16);

        add_round_key(state, ctx->round_key + 224);

        for (int round = 13; round > 0; --round) {
            inv_shift_rows(state);
            inv_sub_bytes(state);
            add_round_key(state, ctx->round_key + round * 16);
            inv_mix_columns(state);
        }

        inv_shift_rows(state);
        inv_sub_bytes(state);
        add_round_key(state, ctx->round_key);

        memcpy(plaintext + i, state, 16);
    }

    return AES256_SUCCESS;
}
