// ============================================================
// Key Expansion (AES-256)
// ============================================================

static void key_expansion(uint8_t* round_key, const uint8_t* key)
{
    int i, j, k;
    uint8_t temp[4];

    for (i = 0; i < 32; ++i) {
        round_key[i] = key[i];
    }

    for (i = 8; i < 60; ++i) {
        k = (i - 1) * 4;
        temp[0] = round_key[k + 0];
        temp[1] = round_key[k + 1];
        temp[2] = round_key[k + 2];
        temp[3] = round_key[k + 3];

        if (i % 8 == 0) {
            // RotWord + SubWord + Rcon
            uint8_t t = temp[0];
            temp[0] = sbox[temp[1]] ^ (i / 8);
            temp[1] = sbox[temp[2]];
            temp[2] = sbox[temp[3]];
            temp[3] = sbox[t];
        } else if (i % 8 == 4) {
            // SubWord
            temp[0] = sbox[temp[0]];
            temp[1] = sbox[temp[1]];
            temp[2] = sbox[temp[2]];
            temp[3] = sbox[temp[3]];
        }

        k = i * 4;
        j = (i - 8) * 4;
        round_key[k + 0] = round_key[j + 0] ^ temp[0];
        round_key[k + 1] = round_key[j + 1] ^ temp[1];
        round_key[k + 2] = round_key[j + 2] ^ temp[2];
        round_key[k + 3] = round_key[j + 3] ^ temp[3];
    }
}

// ============================================================
// AES Core Transformations
// ============================================================

static uint8_t sub_byte(uint8_t byte)
{
    return sbox[byte];
}

static void sub_bytes(uint8_t* state)
{
    for (int i = 0; i < 16; ++i) {
        state[i] = sbox[state[i]];
    }
}

static void inv_sub_bytes(uint8_t* state)
{
    for (int i = 0; i < 16; ++i) {
        state[i] = rsbox[state[i]];
    }
}

static void shift_rows(uint8_t* state)
{
    uint8_t temp;

    // Row 1
    temp = state[1];
    state[1] = state[5];
    state[5] = state[9];
    state[9] = state[13];
    state[13] = temp;

    // Row 2
    temp = state[2];
    state[2] = state[10];
    state[10] = temp;
    temp = state[6];
    state[6] = state[14];
    state[14] = temp;

    // Row 3
    temp = state[3];
    state[3] = state[15];
    state[15] = state[11];
    state[11] = state[7];
    state[7] = temp;
}

static void inv_shift_rows(uint8_t* state)
{
    uint8_t temp;

    // Row 1
    temp = state[13];
    state[13] = state[9];
    state[9] = state[5];
    state[5] = state[1];
    state[1] = temp;

    // Row 2
    temp = state[2];
    state[2] = state[10];
    state[10] = temp;
    temp = state[6];
    state[6] = state[14];
    state[14] = temp;

    // Row 3
    temp = state[7];
    state[7] = state[11];
    state[11] = state[15];
    state[15] = state[3];
    state[3] = temp;
}

static void mix_columns(uint8_t* state)
{
    for (int i = 0; i < 4; ++i) {
        uint8_t a = state[i];
        uint8_t b = state[4 + i];
        uint8_t c = state[8 + i];
        uint8_t d = state[12 + i];

        state[i] = (a << 1) ^ (a >> 7 ? 0x1b : 0);
        if (b >> 7) state[i] ^= b ^ 0x1b;
        else state[i] ^= b;
        state[i] ^= c ^ d;

        state[4 + i] = (b << 1) ^ (b >> 7 ? 0x1b : 0);
        if (c >> 7) state[4 + i] ^= c ^ 0x1b;
        else state[4 + i] ^= c;
        state[4 + i] ^= d ^ a;

        state[8 + i] = (c << 1) ^ (c >> 7 ? 0x1b : 0);
        if (d >> 7) state[8 + i] ^= d ^ 0x1b;
        else state[8 + i] ^= d;
        state[8 + i] ^= a ^ b;

        state[12 + i] = (d << 1) ^ (d >> 7 ? 0x1b : 0);
        if (a >> 7) state[12 + i] ^= a ^ 0x1b;
        else state[12 + i] ^= a;
        state[12 + i] ^= b ^ c;
    }
}

static uint8_t mul(uint8_t x, uint8_t y)
{
    return (((y & 1) * x) ^
            ((y & 2) * (x << 1)) ^
            ((y & 4) * (x << 2)) ^
            ((y & 8) * (x << 3)) ^
            ((y & 16) * (x << 4)) ^
            ((y & 32) * (x << 5)) ^
            ((y & 64) * (x << 6)) ^
            ((y & 128) * (x << 7)));
}

static void inv_mix_columns(uint8_t* state)
{
    for (int i = 0; i < 4; ++i) {
        uint8_t a = state[i];
        uint8_t b = state[4 + i];
        uint8_t c = state[8 + i];
        uint8_t d = state[12 + i];

        state[i] = mul(a, 0x0e) ^ mul(b, 0x0b) ^ mul(c, 0x0d) ^ mul(d, 0x09);
        state[4 + i] = mul(a, 0x09) ^ mul(b, 0x0e) ^ mul(c, 0x0b) ^ mul(d, 0x0d);
        state[8 + i] = mul(a, 0x0d) ^ mul(b, 0x09) ^ mul(c, 0x0e) ^ mul(d, 0x0b);
        state[12 + i] = mul(a, 0x0b) ^ mul(b, 0x0d) ^ mul(c, 0x09) ^ mul(d, 0x0e);
    }
}

static void add_round_key(uint8_t* state, const uint8_t* round_key)
{
    for (int i = 0; i < 16; ++i) {
        state[i] ^= round_key[i * 4];
    }
}

